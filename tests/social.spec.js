  await expect(page.getByText('Lista znajomych jest pusta.',{exact:true})).toBeVisible()
  // List rows carry their relation: no per-row relation requests (N+1) on /friends.
  expect(relationRequests).toEqual([])
  await page.goto('/players/'+aid);await page.getByLabel('Motyw kolorystyczny').selectOption('emerald');await page.getByLabel('Nagłówek',{exact:true}).selectOption('grid');await page.getByRole('button',{name:'Zapisz profil'}).click()
  await expect(page.locator('.ch-profile-hero')).toHaveClass(/ch-theme-emerald.*ch-banner-grid/)
